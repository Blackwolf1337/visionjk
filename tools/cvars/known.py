#!/usr/bin/env python3
"""The names of all cvars this build can use, for cvar_cleanup (codemp/qcommon/cvar/cvar_cleanup.cpp).

usage: tools/cvars/known.py <tree> <output header>

A cvar a config sets that none of these names is, nothing of this version reads: the cleanup offers it at once,
instead of after 30 days without use. The list is generous on purpose, a name too many only keeps a cvar:
- every string literal of the sources of codemp/ that looks like a name (engine, renderers, cgame, ui, game),
- the names of the XCVAR_DEF tables, which only stringify them,
- the cvar words of the menus (cvar, cvarFloat, cvarTest, setcvar ...) and the seta/set lines of the asset configs.
The old names of codemp/qcommon/cvar/cvar_renames.h are taken out: their value went to the new name.
"""
import os
import re
import sys

NAME = rb'[A-Za-z_][A-Za-z0-9_]{1,63}'
LITERAL = re.compile(rb'"(' + NAME + rb')"')
XCVAR = re.compile(rb'XCVAR_DEF\(\s*(' + NAME + rb')')
MENU = re.compile(rb'\b(?:cvar\w*|setcvar|setitemcolor|ownerdrawcvar)\s+"?(' + NAME + rb')', re.I)
CONFIG = re.compile(rb'^\s*seta?\s+(' + NAME + rb')', re.M | re.I)
RENAMED = re.compile(rb'CVAR_RENAME\(\s*"(' + NAME + rb')"')


def walk(root, ends):
    for top, dirs, files in os.walk(root):
        dirs[:] = [d for d in dirs if not d.startswith('.')]
        for f in files:
            if f.lower().endswith(ends):
                yield os.path.join(top, f)


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    tree, out = sys.argv[1], sys.argv[2]
    names = set()
    for path in walk(os.path.join(tree, 'codemp'), ('.c', '.cpp', '.h')):
        text = open(path, 'rb').read()
        names.update(m.group(1).lower() for m in LITERAL.finditer(text))
        names.update(m.group(1).lower() for m in XCVAR.finditer(text))
    for path in walk(os.path.join(tree, 'assets'), ('.menu', '.cfg')):
        text = open(path, 'rb').read()
        if path.lower().endswith('.menu'):
            names.update(m.group(1).lower() for m in MENU.finditer(text))
        else:
            names.update(m.group(1).lower() for m in CONFIG.finditer(text))
    renames = open(os.path.join(tree, 'codemp', 'qcommon', 'cvar', 'cvar_renames.h'), 'rb').read()
    names -= {m.group(1).lower() for m in RENAMED.finditer(renames)}

    lines = ['// generated by tools/cvars/known.py at the build, do not edit: the cvars this build can use, sorted',
             '#define CVAR_KNOWN_COUNT %d' % len(names), 'static const char *const cvarKnown[CVAR_KNOWN_COUNT] = {']
    lines += ['\t"%s",' % n.decode() for n in sorted(names)]
    lines += ['};', '']
    text = '\n'.join(lines)
    os.makedirs(os.path.dirname(out) or '.', exist_ok=True)
    with open(out + '.tmp', 'w') as f:
        f.write(text)
    os.replace(out + '.tmp', out)


if __name__ == '__main__':
    main()
